package com.nit.math;

// Trick 

// % (mod)  -- > last number print krte.

// / (division) --> last number sodun print kerte.

public class ModDivision2 {
	
	public static void main(String[] args) {
        
		System.out.println("%  mod  : - > " +  126 % 10 );
		System.out.println("mod  last number print keto");
		System.out.println(" ----------------------------");
		
		System.out.println("/ division  : - > " + 126 / 10 );
		System.out.println("/ division last number sodun print keto");
		System.out.println("----------------------------------------");
	}
}
